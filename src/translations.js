const lookup = (source, keys) => keys.reduce((value, key) => (value === undefined || value === null ? undefined : value[key]), source)

// t('spec.city') → строка; если в выбранном языке ключа нет, берём английский.
export const useTranslation = (lang) => (key, ...args) => {
  const keys = key.split('.')
  const value = lookup(translations[lang] || translations.en, keys) ?? lookup(translations.en, keys)
  if (value === undefined) return key
  return typeof value === 'function' ? value(...args) : value
}
