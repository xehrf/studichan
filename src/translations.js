export const useTranslation = (lang) => {
  return (key, ...args) => {
    const keys = key.split('.')
    let value = translations[lang] || translations.en

    for (const k of keys) {
      value = value[k]
      if (!value) return key
    }

    if (typeof value === 'function') {
      return value(...args)
    }
    return value
  }
}
